"""Generate the state block of WORKFLOW-INDEX.md from the files that actually know.

The index used to carry a hand-written status table. It drifted within minutes
(index said "r5d awaiting Hy4" while the ledger already held r5d FAIL and r5e was
on disk). This script is the only writer of that block:

    python art/tests/workflow_state.py            # print, do not touch the index
    python art/tests/workflow_state.py --write    # refresh the STATE block in place
    python art/tests/workflow_state.py --check    # exit 1 when the block is stale

Sources: out/qa-asset-verdicts.json, art/env/asset-dependencies.json,
art/comfy/GPU-LOCK.json, art/comfy/ALH/learning-log.jsonl, file mtimes.
No GPU, no render, no verdict: it only reports what is already on disk.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LEDGER = ROOT / "out/qa-asset-verdicts.json"
DEPS = ROOT / "art/env/asset-dependencies.json"
LOCK = ROOT / "art/comfy/GPU-LOCK.json"
ALH = ROOT / "art/comfy/ALH/learning-log.jsonl"
INDEX = ROOT / "WORKFLOW-INDEX.md"
BEGIN = "<!-- STATE:BEGIN"
END = "<!-- STATE:END -->"


def load_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except Exception:
        return default


def latest_verdicts() -> dict[str, dict]:
    rows = load_json(LEDGER, [])
    out: dict[str, dict] = {}
    for row in rows if isinstance(rows, list) else []:
        asset = row.get("asset")
        if not asset:
            continue
        prev = out.get(asset)
        if prev is None or str(row.get("time", "")) >= str(prev.get("time", "")):
            out[asset] = row
    return out


def verdict_for(path: str, verdicts: dict[str, dict]) -> str:
    if not path or path.startswith("none"):
        return "-"
    row = verdicts.get(path)
    if not row:
        return "not-in-ledger"
    flag = " (superseded)" if row.get("superseded") else ""
    return f"{row.get('verdict', '?')}{flag}"


def exists_mark(path: str) -> str:
    if not path or path.startswith("none"):
        return "-"
    return "yes" if (ROOT / path).exists() else "MISSING"


def alh_summary() -> str:
    events = []
    if ALH.exists():
        for line in ALH.read_text(encoding="utf-8-sig").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    counts: dict[str, int] = {}
    for e in events:
        counts[str(e.get("status", "?"))] = counts.get(str(e.get("status", "?")), 0) + 1
    last = events[-1].get("id", "-") if events else "-"
    parts = ", ".join(f"{v} {k}" for k, v in sorted(counts.items()))
    return f"{len(events)} events ({parts}); last {last}"


def stamp(path: Path) -> str:
    if not path.exists():
        return "missing"
    return datetime.fromtimestamp(path.stat().st_mtime).strftime("%d/%m %H:%M:%S")


def dep_state(name: str, element: dict, elements: dict, verdicts: dict[str, dict]) -> str:
    """A dependent asset is blocked while any parent is missing or not PASS."""
    deps = list(element.get("depends_on") or [])
    if not deps:
        return "-"
    bad: list[str] = []
    for d in deps:
        parent = elements.get(d) or {}
        path = str(parent.get("canonical") or "")
        row = verdicts.get(path) if path else None
        if not path or path.startswith("none") or not (ROOT / path).exists():
            bad.append(f"{d}: missing")
        elif not row:
            bad.append(f"{d}: not-in-ledger")
        elif row.get("superseded"):
            bad.append(f"{d}: superseded")
        elif row.get("verdict") != "PASS":
            bad.append(f"{d}: {row.get('verdict')}")
    return "BLOCKED by " + ", ".join(bad) if bad else "clear"


def build_block() -> str:
    deps = load_json(DEPS, {})
    verdicts = latest_verdicts()
    lines = [BEGIN + " (generated by art/tests/workflow_state.py --write; do not edit by hand) -->"]
    lines.append("| Element | Depends on | Gate | Canonical | On disk | Verdict | Regen | Verdict | Declared state |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    elements = deps.get("elements", {}) if isinstance(deps, dict) else {}
    for name, e in elements.items():
        canon = str(e.get("canonical", ""))
        regen = str(e.get("regen", ""))
        state = str(e.get("regen_state") or e.get("canonical_state") or "")
        depends = ", ".join(e.get("depends_on") or []) or "-"
        lines.append(
            f"| `{name}` | {depends} | {dep_state(name, e, elements, verdicts)} | `{canon}` | "
            f"{exists_mark(canon)} | {verdict_for(canon, verdicts)} | `{regen}` | "
            f"{verdict_for(regen, verdicts)} | {state[:120]} |"
        )
    if not elements:
        lines.append("| - | - | - | - | - | - | - | - | no asset-dependencies.json |")

    lock = load_json(LOCK, {})
    if lock:
        lines.append("")
        lines.append(
            f"- **GPU lock:** owner=`{lock.get('owner', '?')}` status=`{lock.get('status', '?')}` "
            f"job=`{lock.get('job', '-')}` started=`{lock.get('started', '-')}`"
        )
        if lock.get("block_reason"):
            lines.append(f"- **Block reason:** {lock['block_reason']}")
    lines.append(f"- **ALH:** {alh_summary()}")
    lines.append(
        f"- **Freshness:** ledger {stamp(LEDGER)} | deps {stamp(DEPS)} | lock {stamp(LOCK)}"
    )
    lines.append(END)
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    pattern = re.compile(re.escape("<!-- STATE:BEGIN") + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(block, text, count=1)
    raise SystemExit("WORKFLOW-INDEX.md has no <!-- STATE:BEGIN ... --> block")


def extract_block(text: str) -> str:
    pattern = re.compile(re.escape("<!-- STATE:BEGIN") + r".*?" + re.escape(END), re.S)
    m = pattern.search(text)
    return m.group(0) if m else ""


def without_stamps(block: str) -> list[str]:
    """Freshness carries write-time stamps; it is display-only, not part of the check."""
    return [ln for ln in block.splitlines() if not ln.startswith("- **Freshness:**")]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="replace the STATE block in WORKFLOW-INDEX.md")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the block differs from a fresh build (hand edit or stale sources)")
    args = ap.parse_args()
    block = build_block()
    if args.check:
        text = INDEX.read_text(encoding="utf-8-sig") if INDEX.exists() else ""
        stored = extract_block(text)
        if not stored:
            print("STALE: WORKFLOW-INDEX.md has no STATE block")
            return 1
        current, fresh = without_stamps(stored), without_stamps(block)
        if current != fresh:
            diff = [f"  - {a}\n  + {b}" for a, b in zip(current, fresh) if a != b][:8]
            print("STALE: WORKFLOW-INDEX state block differs from the sources")
            for d in diff:
                print(d)
            if len(current) != len(fresh):
                print(f"  (lines: stored {len(current)} vs fresh {len(fresh)})")
            print("run: python art/tests/workflow_state.py --write")
            return 1
        print("state block fresh")
        return 0
    if not args.write:
        print(block)
        return 0
    text = INDEX.read_text(encoding="utf-8-sig")
    INDEX.write_text(replace_block(text, block).rstrip() + "\n", encoding="utf-8")
    print(f"updated {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
